// Helper functions
function getUpcomingEvents(daysAhead = 30) {
  const now = new Date();
  const cutoff = new Date(now.getTime() + daysAhead * 24 * 60 * 60 * 1000);
  const year = now.getFullYear();

  return CULTURAL_CALENDAR.events
    .map((event) => {
      const dateKey = `date_${year}`;
      const eventDate = event[dateKey] ? new Date(event[dateKey]) : null;
      return { ...event, eventDate };
    })
    .filter((event) => event.eventDate && event.eventDate >= now && event.eventDate <= cutoff)
    .sort((a, b) => a.eventDate - b.eventDate);
}

function getEventsInRange(startDate, endDate) {
  const start = new Date(startDate);
  const end = new Date(endDate);
  const year = start.getFullYear();

  return CULTURAL_CALENDAR.events
    .map((event) => {
      const dateKey = `date_${year}`;
      const eventDate = event[dateKey] ? new Date(event[dateKey]) : null;
      return { ...event, eventDate };
    })
    .filter((event) => event.eventDate && event.eventDate >= start && event.eventDate <= end)
    .sort((a, b) => a.eventDate - b.eventDate);
}

function findEventsForTalentType(talentType) {
  return CULTURAL_CALENDAR.events.filter((event) =>
    event.talent_fit && event.talent_fit.some((fit) => fit.toLowerCase().includes(talentType.toLowerCase()))
  );
}

function findEventsForBrandCategory(brandCategory) {
  return CULTURAL_CALENDAR.events.filter((event) =>
    event.brand_opportunities && event.brand_opportunities.some((opp) =>
      opp.toLowerCase().includes(brandCategory.toLowerCase())
    )
  );
}

function findEventsForCommunity(community) {
  const events = CULTURAL_CALENDAR.events.filter((event) =>
    event.community && event.community.toLowerCase().includes(community.toLowerCase())
  );
  const moments = CULTURAL_CALENDAR.cultural_moments.filter((moment) =>
    moment.community && moment.community.toLowerCase().includes(community.toLowerCase())
  );
  return { events, moments };
}

function getCurrentBrandCycle() {
  const month = new Date().getMonth() + 1; // 1-12
  return Object.entries(CULTURAL_CALENDAR.brand_cycles)
    .filter(([_, cycle]) => cycle.months.includes(month))
    .map(([name, cycle]) => ({ name, ...cycle }));
}

function getHeritageMonths(month) {
  return CULTURAL_CALENDAR.heritage_months[month] || [];
}

function getCulturalMomentsForMonth(month) {
  const monthStr = month.toString().padStart(2, '0');
  return CULTURAL_CALENDAR.cultural_moments.filter((moment) =>
    moment.date.startsWith(monthStr + '-')
  );
}

function getAnniversariesForMonth(month) {
  const monthStr = month.toString().padStart(2, '0');
  return CULTURAL_CALENDAR.anniversaries_2026.filter((anniversary) =>
    anniversary.date.startsWith(monthStr + '-')
  );
}

function formatEventForSlack(event) {
  const daysUntil = event.eventDate
    ? Math.ceil((event.eventDate - new Date()) / (24 * 60 * 60 * 1000))
    : "TBD";

  let result = `*${event.name}* (${event.category})
_${daysUntil} days away_ - ${event.location}`;

  if (event.community) {
    result += `\nCommunity: ${event.community}`;
  }
  if (event.talent_fit) {
    result += `\nTalent fit: ${event.talent_fit.join(", ")}`;
  }
  if (event.brand_opportunities) {
    result += `\nBrand opps: ${event.brand_opportunities.join(", ")}`;
  }
  if (event.deal_types) {
    result += `\nDeal types: ${event.deal_types.join(", ")}`;
  }
  if (event.avg_deal_value) {
    result += `\nAvg value: ${event.avg_deal_value}`;
  }
  if (event.lead_time_days) {
    result += `\nLead time needed: ${event.lead_time_days} days`;
  }

  return result;
}

function formatCulturalMomentForSlack(moment) {
  let result = `*${moment.name}* (${moment.category})`;
  if (moment.community) {
    result += ` - ${moment.community}`;
  }
  if (moment.note) {
    result += `\n_Note: ${moment.note}_`;
  }
  return result;
}

